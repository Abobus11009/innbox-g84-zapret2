#!/usr/bin/env python3
"""Assemble the portable Python web setup, including UI and router payload."""
import ast
import base64
import pathlib
import textwrap

ROOT = pathlib.Path(__file__).resolve().parents[1]


def source(name):
    path = ROOT / 'setup/g84_setup' / name
    text = path.read_text(encoding='utf-8')
    lines = text.splitlines(keepends=True)
    tree = ast.parse(text)
    removed = set()
    for node in ast.walk(tree):
        if (isinstance(node, ast.ImportFrom) and node.level) or (
            isinstance(node, ast.FunctionDef) and node.name == 'resources'
        ):
            removed.update(range(node.lineno - 1, node.end_lineno))
    return ''.join(line for index, line in enumerate(lines) if index not in removed)


header = '''#!/usr/bin/env python3
"""Innbox G84 local web setup. Generated by scripts/build-setup.py.

Contains the interface and verified router payload; no adjacent files are needed.
Install the Python dependencies once, then run: python g84-setup.py
"""
import base64, pathlib, sys, tempfile
if sys.version_info < (3, 10):
    raise SystemExit('Для мастера нужен Python 3.10 или новее.')
try:
    import paramiko, cryptography
except ImportError:
    raise SystemExit('Установите зависимости: python -m pip install DEPENDENCIES') from None

_RESOURCE_DIRECTORY = None
_RESOURCE_CONTENTS = {
'''.replace('DEPENDENCIES', ' '.join((ROOT / 'requirements.txt').read_text(encoding='utf-8').splitlines()))

for name in ['manifest.env', 'g84-zapret2-payload.tar.gz', 'setup/ui.html']:
    encoded = base64.b64encode((ROOT / name).read_bytes()).decode('ascii')
    header += f'    {name!r}: (\n'
    header += ''.join(f'        {line!r}\n' for line in textwrap.wrap(encoded, 100))
    header += '    ),\n'

header += '''}

def resources():
    global _RESOURCE_DIRECTORY
    if _RESOURCE_DIRECTORY is None:
        _RESOURCE_DIRECTORY = tempfile.TemporaryDirectory(prefix='g84-setup-')
        root = pathlib.Path(_RESOURCE_DIRECTORY.name)
        for name, content in _RESOURCE_CONTENTS.items():
            path = root / name
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(base64.b64decode(content, validate=True))
    return pathlib.Path(_RESOURCE_DIRECTORY.name)

'''
result = header + '\n\n'.join(source(name) for name in ['access.py', 'manager.py', 'app.py'])
result += "\n\nif __name__ == '__main__':\n    main()\n"
compile(result, 'g84-setup.py', 'exec')
(ROOT / 'g84-setup.py').write_text(result, encoding='utf-8', newline='\n')
print('Built standalone g84-setup.py with embedded interface and payload.')
